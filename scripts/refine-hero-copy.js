function updateHero(hero, update) {
  if (!hero || !hero.specialTraits) {
    return;
  }
  hero.specialTraits.summary = update.summary;

  if (typeof update.skill === 'string' && hero.skill && typeof hero.skill === 'object') {
    hero.skill.description = update.skill;
  }

  if (Array.isArray(update.skills) && Array.isArray(hero.skills) && hero.skills.length) {
    update.skills.forEach((description, index) => {
      if (hero.skills[index]) {
        hero.skills[index].description = description;
      }
    });
  }

  if (Array.isArray(update.traits) && Array.isArray(hero.specialTraits.traits)) {
    update.traits.forEach((description, index) => {
      if (hero.specialTraits.traits[index]) {
        hero.specialTraits.traits[index].description = description;
      }
    });
  }

  if (Array.isArray(update.track) && Array.isArray(hero.specialTraits.track)) {
    update.track.forEach((description, index) => {
      if (hero.specialTraits.track[index]) {
        hero.specialTraits.track[index].description = description;
      }
    });
  }
}

function saveJson(path, data) {
  fs.writeFileSync(path, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
}

const catalogPath = 'data/unit-catalog.json';
const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
for (const hero of catalog.heroes || []) {
  if (updates[hero.id]) {
    updateHero(hero, updates[hero.id]);
  }
}
saveJson(catalogPath, catalog);

const overridePath = 'server/data/gm-catalog-overrides.json';
const overrides = JSON.parse(fs.readFileSync(overridePath, 'utf8'));
for (const [id, update] of Object.entries(updates)) {
  if (overrides.heroes && overrides.heroes[id]) {
    updateHero(overrides.heroes[id], update);
  }
}
saveJson(overridePath, overrides);

